#!/usr/bin/env python3
"""Map every ``[M]`` requirement of the PRD to the tests (or demo steps) that cover it.

NFR-MAINT-001 / doc 11 section 8. Requirement IDs are found in Python test files (names and
docstrings, ``FR-VIS-001..009`` and ``FR-DSP-001/004`` expand) and in ``docs/demo/RUNBOOK.md``
(demo-checklist steps). Output is deterministic: ``docs/traceability.md``.

    python3 scripts/traceability.py            write docs/traceability.md
    python3 scripts/traceability.py --check    exit 1 if the file is stale (informational in CI)
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRD = ROOT / "PRD.md"
RUNBOOK = ROOT / "docs" / "demo" / "RUNBOOK.md"
OUT = ROOT / "docs" / "traceability.md"
TEST_GLOBS = ("services/*/tests", "packages/*/tests", "scripts/tests", "eval")

MUST = re.compile(r"\*\*((?:N?FR)-[A-Z]+-\d{3}) \[M\]\*\*")
# FR-VIS-001, FR-VIS-001..009, FR-DSP-001/004; underscores because test names cannot hold "-".
REF = re.compile(r"(?<![A-Za-z])(N?FR)[-_]([A-Z]+)[-_](\d{3})((?:\.\.\d{3}|/\d{3})*)")


def must_requirements(text: str) -> list[str]:
    return sorted(set(MUST.findall(text)))


def expand(kind: str, area: str, first: str, tail: str) -> set[str]:
    """IDs named by one reference, including ``..`` ranges and ``/`` lists."""
    ids = {f"{kind}-{area}-{first}"}
    previous = int(first)
    for sep, num in re.findall(r"(\.\.|/)(\d{3})", tail):
        value = int(num)
        if sep == "..":
            ids.update(f"{kind}-{area}-{n:03d}" for n in range(previous, value + 1))
        else:
            ids.add(f"{kind}-{area}-{num}")
        previous = value
    return ids


def references(text: str) -> set[str]:
    found: set[str] = set()
    for kind, area, first, tail in REF.findall(text):
        found |= expand(kind, area, first, tail)
    return found


def test_files() -> list[Path]:
    files: list[Path] = []
    for pattern in TEST_GLOBS:
        for base in ROOT.glob(pattern):
            files += [p for p in base.rglob("*.py") if "__pycache__" not in p.parts]
    return sorted(files)


def coverage(requirements: list[str]) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    wanted = set(requirements)
    tests: dict[str, list[str]] = {}
    for path in test_files():
        rel = str(path.relative_to(ROOT))
        for requirement in references(path.read_text()) & wanted:
            tests.setdefault(requirement, []).append(rel)
    steps: dict[str, list[str]] = {}
    if RUNBOOK.is_file():
        for number, line in enumerate(RUNBOOK.read_text().splitlines(), 1):
            if not line.lstrip().startswith(("-", "|", "*")) and not re.match(r"\s*\d+\.", line):
                continue
            for requirement in references(line) & wanted:
                steps.setdefault(requirement, []).append(f"RUNBOOK.md:{number}")
    return tests, steps


def render(
    requirements: list[str], tests: dict[str, list[str]], steps: dict[str, list[str]]
) -> str:
    covered = [r for r in requirements if r in tests or r in steps]
    gaps = [r for r in requirements if r not in covered]
    lines = [
        "# Traceability: `[M]` requirements to tests and demo steps",
        "",
        "Generated by `python3 scripts/traceability.py` (PRD NFR-MAINT-001, doc 11 section 8).",
        "Do not edit by hand. A requirement is covered when a Python test file names its ID",
        "(file name, test name or docstring) or a demo-checklist step in",
        "`docs/demo/RUNBOOK.md` does. A test file naming an ID is evidence of intent, not",
        "of completeness: read the test.",
        "",
        f"**{len(covered)} of {len(requirements)} `[M]` requirements covered.**",
        "",
    ]
    if gaps:
        lines += ["## Gaps", "", *(f"- `{r}`" for r in gaps), ""]
    else:
        lines += ["## Gaps", "", "None.", ""]
    lines += ["## Coverage", "", "| Requirement | Tests | Demo steps |", "|---|---|---|"]
    for requirement in requirements:
        t = ", ".join(f"`{p}`" for p in tests.get(requirement, [])) or "—"
        s = ", ".join(f"`{p}`" for p in steps.get(requirement, [])) or "—"
        lines.append(f"| {requirement} | {t} | {s} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the report is stale")
    args = parser.parse_args(argv)
    requirements = must_requirements(PRD.read_text())
    tests, steps = coverage(requirements)
    content = render(requirements, tests, steps)
    gaps = [r for r in requirements if r not in tests and r not in steps]
    print(f"traceability: {len(requirements) - len(gaps)}/{len(requirements)} [M] covered")
    for requirement in gaps:
        print(f"  gap: {requirement}")
    if args.check:
        if not OUT.is_file() or OUT.read_text() != content:
            print("docs/traceability.md is stale: run `make traceability`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
